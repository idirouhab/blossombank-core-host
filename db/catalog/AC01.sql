-- Catalogue source for the database release process.
CREATE TABLE BLSCORE.AC01 (
    INSTITUTION SMALLINT NOT NULL,
    BRANCH SMALLINT NOT NULL,
    ACNUM CHAR(10) NOT NULL,
    CUSTNO CHAR(12) NOT NULL,
    PRDCD CHAR(4) NOT NULL,
    CCY CHAR(3) NOT NULL WITH DEFAULT 'EUR',
    ACSTS CHAR(1) NOT NULL WITH DEFAULT '0',
    AVBAL DECIMAL(15,2) NOT NULL WITH DEFAULT 0,
    AUTBAL DECIMAL(15,2) NOT NULL WITH DEFAULT 0,
    ODLIMIT DECIMAL(15,2) NOT NULL WITH DEFAULT 0,
    LASTDT DATE NOT NULL,
    UPDSEQ INTEGER NOT NULL WITH DEFAULT 0,
    PRIMARY KEY (INSTITUTION,BRANCH,ACNUM)
) IN BLSDB.AC01TS;

CREATE INDEX BLSCORE.AC01X2 ON BLSCORE.AC01
    (CUSTNO,ACSTS,ACNUM) CLUSTER;

CREATE TABLE BLSCORE.MV21 (
    RECNO BIGINT GENERATED ALWAYS AS IDENTITY,
    ACNUM CHAR(10) NOT NULL,
    XREF CHAR(24) NOT NULL,
    MOVCD CHAR(3) NOT NULL,
    CCY CHAR(3) NOT NULL,
    TRNAMT DECIMAL(15,2) NOT NULL,
    VALDATE DATE NOT NULL,
    BOOKTS TIMESTAMP NOT NULL WITH DEFAULT,
    NARR CHAR(40) NOT NULL WITH DEFAULT,
    PRIMARY KEY (RECNO)
) IN BLSDB.MV21TS;

CREATE INDEX BLSCORE.MV21X1 ON BLSCORE.MV21 (ACNUM,VALDATE,RECNO);
CREATE INDEX BLSCORE.MV21X2 ON BLSCORE.MV21 (XREF);

CREATE VIEW BLSCORE.AC01_AVAILABLE AS
    SELECT ACNUM,CUSTNO,CCY,AVBAL-AUTBAL+ODLIMIT AS AVAIL
    FROM BLSCORE.AC01 WHERE ACSTS='0';

COMMENT ON TABLE BLSCORE.AC01 IS 'Account master for office and online region';
COMMENT ON TABLE BLSCORE.MV21 IS 'Movement history retained after day close';
